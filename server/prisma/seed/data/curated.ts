/**
 * Curated layer over the public-domain dataset.
 *
 * free-exercise-db gives us 870+ exercises with step-by-step instructions and
 * public-domain imagery, but its names are inconsistent ("Barbell Bench Press
 * - Medium Grip", "Dumbbell Flyes") and it has no coaching content. These
 * entries:
 *
 *   - rename the movements to what people actually call them in a gym
 *   - add search aliases ("bb bench", "ohp")
 *   - add common mistakes, breathing and tips the dataset lacks
 *   - set the right tracking type (a plank is time, a pull-up is bodyweight)
 *   - seed `popularity` so the big lifts rank first in search
 *
 * `datasetId: null` entries are movements the dataset is missing entirely
 * (pec deck, Bulgarian split squat, ab wheel...) and carry their own
 * instructions.
 */
